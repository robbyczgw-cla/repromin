import { mkdir, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { reduceTest } from "../src/reduce.ts";

const root = resolve(import.meta.dirname, "..");
const config = join(root, "fixtures/playwright.config.ts");

const cases = [
  { id: "A", spec: "fixtures/tests/a-noise.spec.ts", test: "checkout crashes after noisy form filling", confirm: 1 },
  { id: "B", spec: "fixtures/tests/b-joint-state.spec.ts", test: "joint flags required for crash", confirm: 1 },
  { id: "C", spec: "fixtures/tests/c-variable.spec.ts", test: "variable used by later fill", confirm: 1 },
  { id: "D", spec: "fixtures/tests/d-unreachable.spec.ts", test: "secret panel assertion", confirm: 1 },
  { id: "E", spec: "fixtures/tests/e-two-failures.spec.ts", test: "same test two failure modes", confirm: 1 },
  { id: "F", spec: "fixtures/tests/f-flaky.spec.ts", test: "flaky survey action", confirm: 5 },
  { id: "killer", spec: "fixtures/tests/killer.spec.ts", test: "checkout crashes", confirm: 10 },
];

const rows: Array<Record<string, unknown>> = [];

for (const c of cases) {
  process.stderr.write(`\n=== benchmark ${c.id} ===\n`);
  const outDir = join(root, "repromin-out", `bench-${c.id}`);
  const result = await reduceTest({
    specPath: join(root, c.spec),
    testName: c.test,
    confirm: c.confirm,
    searchConfirm: 1,
    timeoutMs: 10_000,
    outDir,
    configPath: config,
    maxRuns: 160,
    noCache: false,
    headed: false,
    dryRun: false,
    keepAssertions: false,
    verbose: true,
  });
  rows.push({
    fixture: c.id,
    originalActions: result.original.actions,
    originalLines: result.original.lines,
    reducedActions: result.reduced?.actions ?? null,
    reducedLines: result.reduced?.lines ?? null,
    reductionRatio:
      result.reduced && result.original.actions
        ? Number((1 - result.reduced.actions / result.original.actions).toFixed(3))
        : null,
    fingerprintMatch: result.fingerprintMatch,
    confirm: `${result.confirmations.passed}/${result.confirmations.total}`,
    runs: result.runs,
    seconds: Number((result.durationMs / 1000).toFixed(1)),
    ok: result.ok,
    rejectReason: result.rejectReason ?? null,
  });
}

await mkdir(join(root, "docs"), { recursive: true });
const header = `| Fixture | Orig actions | Orig lines | Reduced actions | Reduced lines | Ratio | Runs | Time | Same FP | Confirm |
| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- | --- |`;
const body = rows
  .map((r) => {
    const ratio = r.reductionRatio == null ? "—" : `${((r.reductionRatio as number) * 100).toFixed(0)}%`;
    return `| ${r.fixture} | ${r.originalActions} | ${r.originalLines} | ${r.reducedActions ?? "—"} | ${r.reducedLines ?? "—"} | ${ratio} | ${r.runs} | ${r.seconds}s | ${r.fingerprintMatch ? "YES" : "NO"} | ${r.confirm} |`;
  })
  .join("\n");

const md = `# ReproMin v0.1 benchmark

Generated by \`npm run benchmark\`. Each fixture is a local deterministic Playwright test.

${header}
${body}

## How to read this

- **Ratio** is \`1 - reducedActions / originalActions\`.
- **Runs** counts candidate evaluations (cache hits included in the log, not double-executed).
- **Same FP** means the minimized test still produces the original failure fingerprint.
- Fixture F and the killer demo use \`--confirm 5\` and \`--confirm 10\`.
`;

await writeFile(join(root, "docs/benchmark.md"), md);
await writeFile(join(root, "docs/benchmark.json"), JSON.stringify(rows, null, 2) + "\n");
process.stdout.write(md + "\n");
